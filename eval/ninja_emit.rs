//! buildutil — inner build.ninja emission for script-dag derivations
//!
//! A script-dag derivation carries an internal DAG: compile fan-outs
//! (shared flags × N sources) followed by serial steps (links, objcopy,
//! script invocations). buildutil emits a build.ninja into the build cwd and
//! runs the declared ninja tool with full parallelism. The inner ninja is
//! a construction detail — the derivation hash covers the declared plan
//! and sources, never this file.

use crate::spec::{ActivePlan, CompileGroup};

fn escape(token: &str) -> String {
    token
        .replace('$', "$$")
        .replace(' ', "$ ")
        .replace(':', "$:")
}

/// Shell-quote a command token (ninja runs commands through /bin/sh, which
/// would otherwise drop empty tokens and split on spaces), then apply the
/// ninja `$` escape. Plain tokens pass through unquoted for readability.
fn quote(token: &str) -> String {
    let safe = !token.is_empty()
        && token
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"@%+=:,./-_{}".contains(&b));
    if safe {
        token.replace('$', "$$")
    } else {
        format!("'{}'", token.replace('\'', r#"'"'"'"#)).replace('$', "$$")
    }
}

fn stem(source: &str) -> &str {
    let name = source.rsplit('/').next().unwrap_or(source);
    name.rsplit_once('.').map(|(s, _)| s).unwrap_or(name)
}

fn underscorify(source: &str) -> String {
    source
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// The object filename a group produces for one of its sources.
pub fn obj_name(group: &CompileGroup, source: &str) -> String {
    group
        .obj
        .replace("{stem}", stem(source))
        .replace("{path}", &underscorify(source))
}

/// Emit the inner build.ninja. All argv strings must already be
/// exec-resolved (relative `../<repo-rel>` inputs, absolute `{out}`).
pub fn emit(
    plan: &ActivePlan,
    resolve: &dyn Fn(&str) -> Result<String, String>,
) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("# generated by buildutil — script-dag inner build\n");

    let mut all_objs: Vec<String> = Vec::new();
    for (i, group) in plan.compiles.iter().enumerate() {
        let mut flags = Vec::new();
        for flag in &group.flags {
            flags.push(quote(&resolve(flag)?));
        }
        let flags = flags.join(" ");
        out.push_str(&format!("rule g{}\n", i));
        match group.kind.as_str() {
            // The .d files stay on disk for the post-hoc read audit (no
            // `deps = gcc`, which would consume and delete them).
            "cc" => {
                out.push_str(&format!(
                    "  command = {} {} -MMD -MF $out.d -c -o $out $in\n",
                    group.tool, flags
                ));
            }
            "cc-simple" => {
                out.push_str(&format!(
                    "  command = {} {} -c $in -o $out\n",
                    group.tool, flags
                ));
            }
            "nasm" => {
                out.push_str(&format!(
                    "  command = {} {} -o $out $in\n",
                    group.tool, flags
                ));
            }
            other => return Err(format!("unknown compile kind `{}`", other)),
        }
        for source in &group.sources {
            let obj = obj_name(group, source);
            out.push_str(&format!(
                "build {}: g{} ../{}\n",
                escape(&obj),
                i,
                escape(source)
            ));
            all_objs.push(obj);
        }
    }

    // Steps run serially: each depends on every compile object plus the
    // previous step's outputs. `{objs}` expands to the full object list.
    let mut prev_outputs: Vec<String> = Vec::new();
    for (j, step) in plan.steps.iter().enumerate() {
        let mut argv = Vec::new();
        for arg in &step.argv {
            if arg == "{objs}" {
                argv.extend(all_objs.iter().map(|o| quote(o)));
                continue;
            }
            argv.push(quote(&resolve(arg)?));
        }
        let redirect = if step.capture.is_empty() {
            String::new()
        } else {
            format!(" > {}", quote(&resolve(&step.capture)?))
        };
        out.push_str(&format!(
            "rule s{}\n  command = {} {}{}\n",
            j,
            step.tool,
            argv.join(" "),
            redirect
        ));
        if step.capture.is_empty() {
            out.push_str("  pool = console\n");
        }
        let mut outputs = Vec::new();
        for output in &step.outputs {
            outputs.push(escape(&resolve(output)?));
        }
        let mut inputs: Vec<String> = all_objs.iter().map(|o| escape(o)).collect();
        inputs.extend(prev_outputs.iter().cloned());
        out.push_str(&format!(
            "build {}: s{} | {}\n",
            outputs.join(" "),
            j,
            inputs.join(" ")
        ));
        prev_outputs = outputs;
    }

    if let Some(last) = plan.steps.last() {
        let mut defaults = Vec::new();
        for output in &last.outputs {
            defaults.push(escape(&resolve(output)?));
        }
        out.push_str(&format!("default {}\n", defaults.join(" ")));
    } else if !all_objs.is_empty() {
        let objs: Vec<String> = all_objs.iter().map(|o| escape(o)).collect();
        out.push_str(&format!("default {}\n", objs.join(" ")));
    }
    Ok(out)
}

/// Canonical hash lines covering the active plan — appended to the drv
/// preimage so plan edits change the derivation identity.
pub fn hash_lines(plan: &ActivePlan) -> Vec<String> {
    fn tokens(groups: &[&[String]]) -> String {
        let mut bytes = Vec::new();
        for group in groups {
            bytes.extend_from_slice(&(group.len() as u64).to_le_bytes());
            for value in *group {
                bytes.extend_from_slice(&(value.len() as u64).to_le_bytes());
                bytes.extend_from_slice(value.as_bytes());
            }
        }
        crate::crypto::sha256::hash_bytes(&bytes)
    }
    let mut out = Vec::new();
    for group in &plan.compiles {
        out.push(format!(
            "compile: {} {} {} | {} | {} | tokens:{}",
            group.kind,
            group.tool,
            group.obj,
            group.flags.join(" "),
            group.sources.join(" "),
            tokens(&[
                &[group.kind.clone(), group.tool.clone(), group.obj.clone()],
                &group.flags,
                &group.sources
            ]),
        ));
    }
    for step in &plan.steps {
        out.push(format!(
            "step: {} | {} | {} | {} | tokens:{}",
            step.tool,
            step.argv.join(" "),
            step.capture,
            step.outputs.join(" "),
            tokens(&[
                &[step.tool.clone(), step.capture.clone()],
                &step.argv,
                &step.outputs
            ]),
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::spec::Step;

    #[test]
    fn required_check_identity_preserves_argument_boundaries() {
        let mut plan = ActivePlan {
            compiles: vec![],
            steps: vec![Step {
                when: String::new(),
                tool: "sh".into(),
                argv: vec!["-c".into(), "exit 0".into()],
                capture: "verdict".into(),
                outputs: vec!["verdict".into()],
            }],
        };
        let success = hash_lines(&plan);
        plan.steps[0].argv = vec!["-c exit".into(), "0".into()];
        assert_ne!(
            success,
            hash_lines(&plan),
            "joining argv with spaces aliases different validation commands"
        );
    }

    #[test]
    fn emits_rules_builds_and_serial_steps() {
        let plan = ActivePlan {
            compiles: vec![CompileGroup {
                when: String::new(),
                kind: "nasm".into(),
                tool: "nasm".into(),
                flags: vec!["-f".into(), "elf32".into()],
                sources: vec!["boot/a.asm".into(), "boot/b.asm".into()],
                scan_dir: String::new(),
                scan_ext: String::new(),
                scan_exclude: vec![],
                obj: "s2_{stem}.o".into(),
            }],
            steps: vec![
                Step {
                    when: String::new(),
                    tool: "llvm-objcopy".into(),
                    argv: vec![
                        "-O".into(),
                        "binary".into(),
                        "{out}/x.elf".into(),
                        "{out}/x.bin".into(),
                    ],
                    capture: String::new(),
                    outputs: vec!["{out}/x.bin".into()],
                },
                Step {
                    when: String::new(),
                    tool: "ninja".into(),
                    argv: vec!["-C".into(), "build".into(), "install".into()],
                    capture: String::new(),
                    outputs: vec!["{out}/installed".into()],
                },
            ],
        };
        let resolve = |s: &str| Ok(s.replace("{out}", "/o"));
        let text = emit(&plan, &resolve).unwrap();
        assert!(text.contains("rule g0\n  command = nasm -f elf32 -o $out $in\n"));
        assert!(text.contains("build s2_a.o: g0 ../boot/a.asm\n"));
        assert!(text.contains(
            "rule s0\n  command = llvm-objcopy -O binary /o/x.elf /o/x.bin\n  pool = console\n"
        ));
        assert!(text.contains("build /o/x.bin: s0 | s2_a.o s2_b.o\n"));
        assert!(text.contains("rule s1\n  command = ninja -C build install\n  pool = console\n"));
        assert!(text.contains("build /o/installed: s1 | s2_a.o s2_b.o /o/x.bin\n"));
        assert!(text.contains("default /o/installed\n"));

        let lines = hash_lines(&plan);
        assert_eq!(lines.len(), 3);
        assert!(lines[0].starts_with("compile: nasm nasm s2_{stem}.o"));
    }
}
